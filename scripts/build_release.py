"""Build an allowlisted, deterministic archive; never walk the virtual environment."""
import argparse
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
VERSION = next(line.split(':', 1)[1].strip() for line in
               (ROOT / 'plugin/plugin.yaml').read_text().splitlines() if line.startswith('version:'))


def build(output: Path) -> None:
    files = [ROOT / name for name in ('.gitignore', 'README.md', 'LICENSE', 'requirements-worker.txt',
              'requirements-test.txt', 'requirements.lock.txt', 'requirements-worker.lock.txt', 'EVIDENCE.md') if (ROOT / name).is_file()]
    for folder in ('plugin', 'tests', 'scripts', 'docs'):
        # Release-owned top-level files only. Never package diagnostic trees,
        # installed test dependencies, reports generated by research, or caches.
        files.extend(p for p in (ROOT / folder).glob('*')
                     if p.is_file() and not p.is_symlink() and p.name != 'portable.json'
                     and p.suffix in ('.py', '.yaml', '.md', '.json'))
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for file in sorted(set(files)):
            info = zipfile.ZipInfo('hermes-perplexity-pro/' + file.relative_to(ROOT).as_posix())
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, file.read_bytes())
    print(output.resolve())


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / f'dist/hermes-perplexity-pro-{VERSION}.zip')
    build(parser.parse_args().output)
